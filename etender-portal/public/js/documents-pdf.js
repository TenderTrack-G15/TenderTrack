/*
 * The portal's document downloads, as PDF files:
 *   - one tender document, and all of a tender's documents in one file
 *     (the public tender page);
 *   - "All documents" for the procurement officer (Department console): the
 *     tender's documents, every bid with the documents its supplier confirmed,
 *     and each bidder's registration documents.
 * Demonstration documents are clearly marked as such.
 */

import { PdfDocument, pdfFileName } from './pdf.js';
import { date, dateTime, money, downloadFile } from './ui.js';
import { lines, STANDARD_DOCUMENTS } from './tenders-data.js';

const FOOTER = 'eTender Demo Portal — a demonstration for the TenderTrack student project, not a government document';
const DEMO_NOTE = 'DEMONSTRATION DOCUMENT – generated by the eTender Demo Portal for the TenderTrack student project. '
  + 'It is not an official tender document.';
const DOC_STATUS = { not_submitted: 'Not provided', submitted: 'Submitted', verified: 'Verified', expired: 'Expired' };
const REG_STATUS = { awaiting_verification: 'Awaiting verification', verified: 'Verified', not_approved: 'Not approved' };

/** Saves a { fileName, pdf } from the functions below. */
export function savePdf({ fileName, pdf }) {
  downloadFile(fileName, pdf.output(), 'application/pdf');
}

/** A department file is a link; anything else is generated here. */
function fileLink(doc) {
  return doc && doc.file_url && /^https?:\/\//i.test(doc.file_url) ? doc.file_url : null;
}

/** The documents a tender pack offers: the department's own list, or the usual six. */
export function tenderDocumentNames(pack) {
  return pack.documents.length ? [...new Set(pack.documents.map((d) => d.name))] : STANDARD_DOCUMENTS;
}

/** Writes one tender document into [pdf], starting with its name as a heading. */
function writeTenderDocument(pdf, pack, name, { first = false } = {}) {
  const t = pack.tender;
  const d = pack.details || {};
  const doc = pack.documents.find((x) => x.name === name);
  const link = fileLink(doc);
  if (!first) pdf.newPage();
  if (!first) pdf.text(name, { size: 16, bold: true, lead: 21 }).text(`${t.reference_number} – ${t.title} · ${t.department}`, { size: 10, color: '0.40 0.43 0.47', lead: 14 }).space(8);

  if (link) {
    pdf.paragraph('This document is a file attached by the department. Open it here:');
    pdf.paragraph(link, { bold: true });
    if (doc.doc_type) pdf.note(doc.doc_type);
    return;
  }
  pdf.note(DEMO_NOTE);
  pdf.keyValues([
    ['Tender number', t.reference_number],
    ['Issuing department', t.department],
    ['Category', t.category],
    ['Closing date and time', dateTime(t.closing_date)],
    ['Contract period', t.contract_period_months ? `${t.contract_period_months} months` : null],
  ]);
  pdf.heading('Description', 2).paragraph(t.description || 'Not stated.');
  if (d.scope_overview) pdf.heading('Scope of work', 2).paragraph(d.scope_overview);
  if (lines(d.deliverables).length) pdf.heading('Deliverables', 2).bullets(lines(d.deliverables));
  if (d.technical_specs) pdf.heading('Technical specifications', 2).paragraph(d.technical_specs);
  if (d.quantity_requirements) pdf.heading('Quantity requirements', 2).paragraph(d.quantity_requirements);
  if (lines(d.required_documents).length) pdf.heading('Documents to submit with the bid', 2).bullets(lines(d.required_documents));
  if (d.technical_weight != null || d.financial_weight != null) {
    pdf.heading('Evaluation', 2).keyValues([
      ['Technical evaluation', d.technical_weight != null ? `${d.technical_weight}%` : null],
      ['Financial evaluation', d.financial_weight != null ? `${d.financial_weight}%` : null],
      ['Preference point system', d.preference_points || null],
    ]);
  }
  if (d.query_contact_name || d.query_contact_email) {
    pdf.heading('Queries', 2).keyValues([
      ['Contact person', d.query_contact_name], ['Email address', d.query_contact_email], ['Telephone number', d.query_contact_phone],
    ]);
  }
}

/** One tender document as a PDF: { fileName, pdf }. */
export function tenderDocumentPdf(pack, name) {
  const t = pack.tender;
  const pdf = new PdfDocument({ title: name, subtitle: `${t.reference_number} – ${t.title} · ${t.department}`, footer: FOOTER });
  writeTenderDocument(pdf, pack, name, { first: true });
  return { fileName: pdfFileName(t.reference_number, name), pdf };
}

/** Every document of a tender in one PDF, each starting on a new page: { fileName, pdf }. */
export function allTenderDocumentsPdf(pack) {
  const t = pack.tender;
  const names = tenderDocumentNames(pack);
  const pdf = new PdfDocument({ title: `Tender documents — ${t.reference_number}`, subtitle: `${t.title} · ${t.department}`, footer: FOOTER });
  pdf.keyValues([['Closing date and time', dateTime(t.closing_date)], ['Documents in this file', String(names.length)]]);
  pdf.heading('Contents', 2).bullets(names.map((n, i) => [`${i + 1}.`, n]));
  for (const name of names) writeTenderDocument(pdf, pack, name);
  return { fileName: pdfFileName(t.reference_number, 'all documents'), pdf };
}

/**
 * The procurement officer's "All documents" file for one tender.
 *   tender     the console's tender row (with the internal budget)
 *   pack       the tender pack (loadPack), or null if it could not be read
 *   bids       the tender's bids that were not withdrawn
 *   suppliers  the bidders' registrations: id, company_name, csd_number, status
 *   documents  the bidders' registration documents (supplier_documents rows)
 *   officer    the signed-in officer's name
 */
export function officerDocumentsPdf({ tender: t, pack, bids, suppliers, documents, officer }) {
  const sealed = t.status === 'published';
  const required = pack ? lines((pack.details || {}).required_documents) : [];
  const supplierOf = (id) => suppliers.find((s) => s.id === id);
  const pdf = new PdfDocument({ title: `All documents — ${t.reference_number}`, subtitle: `${t.title} · ${t.department}`, footer: FOOTER });

  pdf.heading('Tender');
  pdf.keyValues([
    ['Status', { published: 'Open for bids', under_evaluation: 'Under evaluation', awarded: 'Awarded', in_progress: 'Awarded · in progress', completed: 'Completed' }[t.status] || t.status],
    ['Closing date and time', dateTime(t.closing_date)],
    ['Estimated budget (internal)', money(t.estimated_budget)],
    ['Bids received', String(bids.length)],
    t.awarded_supplier_name ? ['Awarded to', `${t.awarded_supplier_name} · ${money(t.awarded_value)}`] : null,
    ['Prepared by', `${officer || 'Procurement officer'} · ${dateTime(new Date().toISOString())}`],
  ].filter(Boolean));
  pdf.note(`Confidential: for the evaluation of this tender only.${sealed ? ' Bidding is still open, so bid prices stay sealed.' : ''}`);

  pdf.heading('Bid documents');
  if (!bids.length) pdf.paragraph('No bids have been received.');
  const ordered = [...bids].sort((a, b) => (sealed
    ? new Date(a.submitted_at) - new Date(b.submitted_at)
    : Number(a.bid_value) - Number(b.bid_value)));
  for (const b of ordered) {
    const s = supplierOf(b.supplier_id);
    const confirmed = b.submitted_documents || [];
    const expected = required.length ? required : confirmed;
    pdf.heading(`${b.supplier_name} · ${b.reference}`, 2);
    pdf.keyValues([
      ['CSD number', s ? s.csd_number : null],
      ['Registration', s ? REG_STATUS[s.status] || s.status : 'Not registered'],
      ['Submitted', dateTime(b.submitted_at)],
      ['Total bid price', sealed ? 'Sealed until bidding closes' : money(b.bid_value)],
      ['Preference claimed', b.preference_claim || null],
      ['Bid validity', b.validity_days ? `${b.validity_days} days` : null],
      ['Documents confirmed', `${b.documents_received} of ${b.documents_required}`],
    ]);
    if (expected.length) {
      pdf.bullets(expected.map((name) => (confirmed.includes(name) ? ['[x]', name] : ['[  ]', `${name} — not confirmed`])));
    } else {
      pdf.note('This tender lists no required documents.');
    }
    if (b.notes) pdf.text('Cover note', { bold: true, size: 9.5 }).paragraph(b.notes, { size: 9.5 });
  }

  pdf.heading('Registration documents of the bidders');
  const bidders = [...new Set(ordered.map((b) => b.supplier_id).filter(Boolean))];
  if (!bidders.length) pdf.paragraph('No registered bidders.');
  for (const id of bidders) {
    const s = supplierOf(id);
    const docs = documents.filter((d) => d.supplier_id === id).sort((a, b) => a.name.localeCompare(b.name));
    pdf.heading(s ? `${s.company_name} · ${s.csd_number}` : ordered.find((b) => b.supplier_id === id).supplier_name, 2);
    if (!docs.length) { pdf.note('No registration documents on record.'); continue; }
    pdf.keyValues(docs.map((d) => [d.name, [
      DOC_STATUS[d.status] || d.status,
      d.reference ? `ref. ${d.reference}` : null,
      d.expires_at ? `${d.status === 'expired' ? 'expired' : 'expires'} ${date(d.expires_at)}` : null,
      d.file_url ? d.file_url : null,
    ].filter(Boolean).join(' · ')]), { keyWidth: 200, size: 9.5 });
  }

  if (pack) {
    const names = tenderDocumentNames(pack);
    pdf.heading('Tender documents');
    pdf.paragraph(`The ${names.length} documents of the tender pack follow, each on a new page.`);
    pdf.bullets(names.map((n, i) => [`${i + 1}.`, n]));
    for (const name of names) writeTenderDocument(pdf, pack, name);
  }
  return { fileName: pdfFileName(t.reference_number, 'all documents'), pdf };
}
