/*
 * Reading tenders. The public list comes from the view tenders_public, which
 * anyone may read and which hides the estimated budget until a tender is
 * awarded. The tender pack (details, eligibility, documents, updates) is
 * readable by anyone once a tender is published.
 */

import { sb, rows } from './client.js';
import { badge } from './ui.js';

const LIST_COLUMNS = 'id, reference_number, title, description, department, category, status, closing_date, '
  + 'published_at, created_at, contract_period_months, awarded_supplier_name, awarded_value, awarded_at, estimated_budget';

export async function listTenders() {
  return rows(sb.from('tenders_public').select(LIST_COLUMNS).order('closing_date', { ascending: true }));
}

/** Which tab a tender belongs on, as on the official portals: advertised, closed or awarded. */
export function tabOf(t) {
  if (['awarded', 'in_progress', 'completed'].includes(t.status)) return 'awarded';
  if (t.status === 'published' && new Date(t.closing_date).getTime() > Date.now()) return 'advertised';
  return 'closed';
}

export async function loadPack(tenderId) {
  const [tender, details, eligibility, documents, updates] = await Promise.all([
    rows(sb.from('tenders_public').select(LIST_COLUMNS).eq('id', tenderId).limit(1)),
    rows(sb.from('tender_details').select('*').eq('tender_id', tenderId).limit(1)),
    rows(sb.from('tender_eligibility').select('*').eq('tender_id', tenderId).order('sequence')),
    rows(sb.from('tender_documents').select('*').eq('tender_id', tenderId).order('name')),
    rows(sb.from('tender_updates').select('*').eq('tender_id', tenderId).order('published_at', { ascending: false })),
  ]);
  if (!tender.length) throw new Error('That tender does not exist or has not been published.');
  return { tender: tender[0], details: details[0] || null, eligibility, documents, updates };
}

export function lines(text) {
  return String(text || '').split('\n').map((l) => l.trim()).filter(Boolean);
}

/** The six documents every tender pack offers, in the usual order. */
export const STANDARD_DOCUMENTS = [
  'Request for Proposal (RFP)', 'Terms of Reference (TOR)', 'Specifications',
  'Pricing Schedule', 'Tender Forms (SBD)', 'Contract Draft',
];

/**
 * A plain-text stand-in for a tender document, for when the department has
 * not attached a file. Clearly marked as a demonstration document.
 */
export function placeholderDocument(pack, docName) {
  const t = pack.tender;
  const d = pack.details || {};
  const out = [
    `${docName}`,
    `${t.reference_number} – ${t.title}`,
    `${t.department}`,
    '',
    'DEMONSTRATION DOCUMENT – generated by the eTender Demo Portal for the TenderTrack student project.',
    'It is not an official tender document.',
    '',
    `Closing date: ${new Date(t.closing_date).toLocaleString('en-ZA')}`,
    '',
    'Description',
    t.description || '—',
    '',
  ];
  if (d.scope_overview) out.push('Scope of work', d.scope_overview, '');
  if (d.deliverables) out.push('Deliverables', ...lines(d.deliverables).map((l) => `  - ${l}`), '');
  if (d.technical_specs) out.push('Technical specifications', d.technical_specs, '');
  if (d.required_documents) out.push('Documents to submit with the bid', ...lines(d.required_documents).map((l) => `  - ${l}`), '');
  if (d.technical_weight || d.financial_weight) {
    out.push('Evaluation', `  Technical: ${d.technical_weight ?? '—'}%   Financial: ${d.financial_weight ?? '—'}%`, `  Preference: ${d.preference_points || '—'}`, '');
  }
  if (d.query_contact_name) out.push('Queries', `  ${d.query_contact_name} · ${d.query_contact_email} · ${d.query_contact_phone}`);
  return out.join('\r\n');
}

/** 80/20 preference points for a B-BBEE level (as used in the demo). */
export function preferencePoints(level) {
  return { 1: 20, 2: 18, 3: 14, 4: 12, 5: 8, 6: 6, 7: 4, 8: 2 }[Number(level)] ?? 0;
}

/** The status badge used on every list and page. */
export function statusBadge(t) {
  const tab = tabOf(t);
  if (tab === 'advertised') return badge('Open for bids', 'success');
  if (tab === 'awarded') {
    if (t.status === 'completed') return badge('Completed', 'neutral');
    return t.status === 'in_progress' ? badge('Awarded · in progress', 'success') : badge('Awarded', 'info');
  }
  return badge(t.status === 'under_evaluation' ? 'Closed · under evaluation' : 'Closed', 'warn');
}

